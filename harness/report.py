"""Render runs/SUMMARY.md and verify the run evidence.

    python -m harness.report --write    regenerate runs/SUMMARY.md
    python -m harness.report --check    read-only; exit 1 unless the evidence is complete,
                                        bound to the current task files and SUMMARY.md is current
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from .agent_runs import (AGENTS, BOUNDARY_STATEMENT, MAX_ATTEMPTS, TRIALS, TRIAL_RE,
                         grader_digest, list_attempts, read_json, sha256_file, task_auditor_digest,
                         task_hash)
from .tasks import CORPUS_PATH, RUNS_DIR, TASKS_DIR, TaskError, load_corpus, load_tasks, utf8_stdout

SOURCES = ("agent", "environment", "grader")
HEADER = ("| Task | Agent | Passed | Agent failures | Environment failures "
          "| Grader failures | Contaminated |")
REQUIRED_FILES = ("transcript.jsonl", "final.patch", "meta.json", "grade.json",
                  "llm_grade.json", "audit.json", "classification.json")


# --- collection ------------------------------------------------------------

def collect(runs_dir: Path) -> list[dict]:
    """One record per trial: its final (last) attempt. Read-only."""
    runs_dir = Path(runs_dir)
    recs = []
    for tdir in sorted(runs_dir.glob("*/*/trial-*")):
        if not tdir.is_dir() or not TRIAL_RE.match(tdir.name) or tdir.parts[-3].startswith("_"):
            continue
        attempts = list_attempts(tdir)
        if not attempts:
            continue
        n, adir = attempts[-1]
        grade = read_json(adir / "grade.json") or {}
        cls = read_json(adir / "classification.json") or {}
        llm = read_json(adir / "llm_grade.json") or {}
        meta = read_json(adir / "meta.json") or {}
        incomplete = meta.get("status") != "complete"
        recs.append({
            "task": tdir.parts[-3], "agent": tdir.parts[-2],
            "trial": int(tdir.name.split("-")[1]), "attempt": n, "attempts": len(attempts),
            "dir": adir, "verdict": grade.get("verdict", "—"),
            "outcome": "incomplete" if incomplete else cls.get("outcome"),
            "source": cls.get("failure_source"),
            "evidence": ("attempt " + str(meta.get("status", "unknown")) + ": "
                         + _first_line(meta.get("error"))) if incomplete else cls.get("evidence", ""),
            "classified_by": cls.get("classified_by", ""),
            "llm_status": llm.get("status"), "llm_verdict": llm.get("verdict"),
            "meta": meta,
        })
    return recs


def _first_line(text) -> str:
    lines = [ln for ln in str(text or "").strip().splitlines() if ln.strip()]
    return lines[-1].strip() if lines else "no error recorded"


def collect_all(runs_dir: Path) -> list[dict]:
    """One record per ATTEMPT (superseded ones included). Read-only."""
    runs_dir = Path(runs_dir)
    out = []
    for tdir in sorted(runs_dir.glob("*/*/trial-*")):
        if not tdir.is_dir() or not TRIAL_RE.match(tdir.name) or tdir.parts[-3].startswith("_"):
            continue
        attempts = list_attempts(tdir)
        for n, adir in attempts:
            meta = read_json(adir / "meta.json") or {}
            cls = read_json(adir / "classification.json") or {}
            aud = read_json(adir / "audit.json") or {}
            out.append({"task": tdir.parts[-3], "agent": tdir.parts[-2],
                        "trial": int(tdir.name.split("-")[1]), "attempt": n,
                        "final": n == attempts[-1][0], "attempts": len(attempts),
                        "status": meta.get("status", "unknown"), "error": meta.get("error"),
                        "outcome": cls.get("outcome"), "source": cls.get("failure_source"),
                        "evidence": cls.get("evidence", ""),
                        "clean": aud.get("clean"), "hits": aud.get("hits") or [],
                        "review": aud.get("review_required") or [],
                        "review_cleared": cls.get("review_cleared")})
    return out


# --- rendering -------------------------------------------------------------

def _cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def render(recs: list[dict], all_recs: list[dict] | None = None) -> str:
    lines = ["# Agent runs summary", "",
             "Generated by `python -m harness.report --write` from "
             "`runs/<task>/<agent>/trial-<n>/attempt-<m>/`. A trial's result is its last "
             "attempt; earlier attempts (environment or contaminated only) stay in the repo. "
             "k/N counts trials. Every failure source was confirmed by the reviewer.", ""]
    groups: dict[tuple, list[dict]] = {}
    for r in recs:
        groups.setdefault((r["task"], r["agent"]), []).append(r)

    lines += ["## Pass rate", "", HEADER, "|" + "---|" * 7]
    for (task, agent), rs in sorted(groups.items()):
        passed = sum(1 for r in rs if r["outcome"] == "pass")
        counts = [sum(1 for r in rs if r["outcome"] in ("fail", "error") and r["source"] == s)
                  for s in SOURCES]
        contaminated = sum(1 for r in rs if r["outcome"] == "contaminated")
        lines.append(f"| {task} | {agent} | {passed}/{len(rs)} | "
                     + " | ".join(str(c) for c in counts) + f" | {contaminated} |")

    lines += ["", "## Failure sources", "", "| Source | Trials |", "|---|---|"]
    for s in SOURCES:
        lines.append(f"| {s} | {sum(1 for r in recs if r['outcome'] in ('fail', 'error') and r['source'] == s)} |")
    lines.append(f"| contaminated | {sum(1 for r in recs if r['outcome'] == 'contaminated')} |")
    lines.append(f"| unclassified | {sum(1 for r in recs if r['outcome'] not in ('pass', 'contaminated') and r['source'] not in SOURCES)} |")

    cont = [r for r in recs if r["outcome"] == "contaminated"]
    lines += ["", "## Contaminated trials", ""]
    if cont:
        lines += ["| Trial | Evidence |", "|---|---|"]
        for r in cont:
            lines.append(f"| {r['task']}/{r['agent']}/trial-{r['trial']} | {_cell(r['evidence'])} |")
    else:
        lines.append("None.")

    graded = [r for r in recs if r["llm_status"] == "graded" and r["verdict"] in ("PASS", "FAIL")]
    agree = [r for r in graded if r["llm_verdict"] == r["verdict"]]
    lines += ["", "## LLM grader vs deterministic grade", "",
              f"- Graded runs compared: {len(graded)}; agree: {len(agree)}; "
              f"disagree: {len(graded) - len(agree)}",
              f"- Not graded (empty patch): {sum(1 for r in recs if r['llm_status'] == 'not_graded')}",
              f"- LLM grade error or missing: "
              f"{sum(1 for r in recs if r['llm_status'] not in ('graded', 'not_graded'))}"]
    dis = [r for r in graded if r["llm_verdict"] != r["verdict"]]
    if dis:
        lines += ["", "| Trial | Deterministic | LLM |", "|---|---|---|"]
        for r in dis:
            lines.append(f"| {r['task']}/{r['agent']}/trial-{r['trial']} | {r['verdict']} | {r['llm_verdict']} |")

    fails = [r for r in recs if r["outcome"] != "pass"]
    if fails:
        lines += ["", "## Non-pass trials", "",
                  "| Trial | Attempts | Outcome | Source | Classified by | Evidence |",
                  "|---|---|---|---|---|---|"]
        for r in fails:
            lines.append(f"| {r['task']}/{r['agent']}/trial-{r['trial']} | {r['attempts']} "
                         f"| {r['outcome'] or '—'} | {r['source'] or '—'} | {r['classified_by']} "
                         f"| {_cell(r['evidence'])} |")

    lines += ["", "## Run settings", ""]
    for agent in AGENTS:
        ms = [r["meta"] for r in recs if r["agent"] == agent and r["meta"]]
        if not ms:
            continue
        def uniq(key):
            vals = sorted({str(m.get(key)) for m in ms})
            return ", ".join(vals)
        lines += [f"- **{agent}**: cli `{uniq('cli_version')}`; requested model `{uniq('requested_model')}`"
                  + (f", effort `{uniq('requested_effort')}`" if agent == "codex" else "")
                  + f"; observed model `{uniq('observed_model')}`; timeout {uniq('timeout_s')} s; "
                  + (f"file-tool scope `{uniq('read_scope')}`; " if agent == "claude" else "")
                  + f"{len(ms)} trials"]
        leak = sorted({x for m in ms for x in (m.get("known_context_leak") or [])})
        for x in leak:
            lines.append(f"  - known context leak: {x}")
        notes = sorted({m["observed_model_note"] for m in ms if m.get("observed_model_note")})
        for x in notes:
            lines.append(f"  - {x}")
        b = next((m.get("boundary") for m in ms if m.get("boundary")), None)
        probe = (b.get("probe") if isinstance(b, dict) and "probe" in b else b) or {}
        if probe:
            lines.append("  - boundary probe: " + ", ".join(
                _route(k, v) for k, v in sorted(probe.items()) if not k.startswith("_")))
    lines += ["", f"**Boundary.** {BOUNDARY_STATEMENT}"]
    lines += _all_attempts(all_recs if all_recs is not None else [])
    return "\n".join(lines) + "\n"


def _route(key, value) -> str:
    if isinstance(value, dict):
        return f"{key}={value.get('result') or value.get('verdict')}"
    return f"{key}={value}"


def _all_attempts(rs: list[dict]) -> list[str]:
    lines = ["", "## All attempts", ""]
    if not rs:
        return lines + ["No attempts recorded."]
    per_trial: dict[tuple, int] = {}
    for r in rs:
        per_trial[(r["task"], r["agent"], r["trial"])] = r["attempts"]
    dist: dict[int, int] = {}
    for n in per_trial.values():
        dist[n] = dist.get(n, 0) + 1
    lines.append(f"- Trials: {len(per_trial)}; attempts: {len(rs)}; attempts per trial: "
                 + ", ".join(f"{n} attempt(s) x {c}" for n, c in sorted(dist.items())))
    retried = [r for r in rs if not r["final"]]
    lines += ["", "### Retries (superseded attempts)", ""]
    if retried:
        lines += ["| Attempt | Status | Outcome | Source | Why it was retried |", "|---|---|---|---|---|"]
        for r in retried:
            why = _first_line(r["error"]) if r["status"] != "complete" else r["evidence"]
            lines.append(f"| {_aid(r)} | {r['status']} | {r['outcome'] or '—'} | {r['source'] or '—'} "
                         f"| {_cell(why)} |")
    else:
        lines.append("None.")
    bad = [r for r in rs if r["outcome"] == "contaminated" or r["clean"] is False]
    lines += ["", "### Contamination incidents (including ones followed by a clean retry)", ""]
    if bad:
        lines += ["| Attempt | Final | Evidence |", "|---|---|---|"]
        for r in bad:
            hit = r["hits"][0]["text"] if r["hits"] else r["evidence"]
            lines.append(f"| {_aid(r)} | {'yes' if r['final'] else 'no'} | {_cell(hit)} |")
    else:
        lines.append("None.")
    inc = [r for r in rs if r["status"] != "complete"]
    lines += ["", "### Incomplete attempts", ""]
    if inc:
        lines += ["| Attempt | Status | Error |", "|---|---|---|"]
        for r in inc:
            lines.append(f"| {_aid(r)} | {r['status']} | {_cell(_first_line(r['error']))} |")
    else:
        lines.append("None.")
    rev = [r for r in rs if r["review"]]
    lines += ["", "### Host-access patterns needing review", ""]
    if rev:
        lines += ["| Attempt | Patterns | First hit | Cleared |", "|---|---|---|---|"]
        for r in rev:
            first = r["review"][0]
            lines.append(f"| {_aid(r)} | {len(r['review'])} "
                         f"| {_cell(first['where'] + ': ' + first['text'])} "
                         f"| {_cell(r['review_cleared'] or 'NOT CLEARED')} |")
    else:
        lines.append("None.")
    return lines


def _aid(r: dict) -> str:
    return f"{r['task']}/{r['agent']}/trial-{r['trial']}/attempt-{r['attempt']}"


def write_summary(runs_dir: Path = RUNS_DIR) -> Path:
    runs_dir = Path(runs_dir)
    runs_dir.mkdir(parents=True, exist_ok=True)
    out = runs_dir / "SUMMARY.md"
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(collect(runs_dir), collect_all(runs_dir)))
    return out


# --- verification ----------------------------------------------------------

def check(runs_dir: Path, tasks_dir: Path = TASKS_DIR, corpus_path: Path = CORPUS_PATH) -> list[str]:
    """Strictly read-only. Returns the list of problems (empty = evidence is complete)."""
    from .llm_grade import MODEL as LLM_MODEL
    runs_dir = Path(runs_dir)
    problems: list[str] = []
    try:
        corpus = load_corpus(Path(corpus_path))
        corpus_ids = [t["id"] for t in corpus["tasks"]]
    except (TaskError, KeyError) as e:
        return [f"corpus: {e}"]
    try:
        tasks = {t.id: t for t in load_tasks(Path(tasks_dir))}
    except TaskError as e:
        return [f"tasks: {e}"]

    for tid in corpus_ids:
        task = tasks.get(tid)
        if task is None:
            problems.append(f"{tid}: in corpus.json but not in tasks/")
            continue
        cur = {"task_hash": task_hash(task), "grader_digest": grader_digest(task),
               "auditor_digest": task_auditor_digest(task)[0],
               "prompt_sha": sha256_file(task.path / "grader_prompt.md"), "llm_model": LLM_MODEL}
        for agent in AGENTS:
            for n in range(1, TRIALS + 1):
                tdir = runs_dir / tid / agent / f"trial-{n}"
                where = f"{tid}/{agent}/trial-{n}"
                attempts = list_attempts(tdir)
                if not attempts:
                    problems.append(f"{where}: missing trial (no attempts)")
                    continue
                if [a for a, _ in attempts] != list(range(1, len(attempts) + 1)):
                    problems.append(f"{where}: attempt numbers not contiguous from 1")
                if len(attempts) > MAX_ATTEMPTS:
                    problems.append(f"{where}: more than {MAX_ATTEMPTS} attempts")
                for i, (m, adir) in enumerate(attempts):
                    final = i == len(attempts) - 1
                    label = f"{where}/attempt-{m}"
                    meta = read_json(adir / "meta.json")
                    if not isinstance(meta, dict):
                        problems.append(f"{label}: missing or invalid meta.json")
                        continue
                    status = meta.get("status")
                    if status == "incomplete":
                        # allowed only as a superseded attempt; it used up one attempt
                        if final:
                            problems.append(f"{label}: final attempt is incomplete (retry or investigate)")
                        elif not meta.get("error"):
                            problems.append(f"{label}: incomplete attempt without a recorded error")
                        continue
                    if status != "complete":
                        problems.append(f"{label}: meta.json status is {status!r} (never finalised)")
                        continue
                    cls = read_json(adir / "classification.json") or {}
                    if not final:
                        ok = cls.get("confirmed") and not cls.get("stale") and (
                            cls.get("outcome") == "contaminated"
                            or cls.get("failure_source") == "environment")
                        if not ok:
                            problems.append(f"{label}: non-final attempt is not confirmed environment/contaminated")
                    problems += _check_attempt(label, adir, cur)

    expected = runs_dir / "SUMMARY.md"
    want = render(collect(runs_dir), collect_all(runs_dir))
    try:
        have = expected.read_bytes().decode("utf-8")
    except OSError:
        problems.append("SUMMARY.md: missing (run --write)")
    else:
        if have != want:
            problems.append("SUMMARY.md: differs from the render (run --write)")
    return problems


def _check_attempt(label, adir, cur) -> list[str]:
    """Evidence and hash bindings of ONE complete attempt (final or superseded)."""
    cur_task_hash, prompt_sha, llm_model = cur["task_hash"], cur["prompt_sha"], cur["llm_model"]
    problems = []
    for name in REQUIRED_FILES:
        if not (adir / name).is_file():
            problems.append(f"{label}: missing {name}")
    if problems:
        return problems
    patch_sha = sha256_file(adir / "final.patch")
    grade, llm, aud, cls = (read_json(adir / n) for n in
                            ("grade.json", "llm_grade.json", "audit.json", "classification.json"))
    for name, data in (("grade.json", grade), ("llm_grade.json", llm),
                       ("audit.json", aud), ("classification.json", cls)):
        if not isinstance(data, dict):
            problems.append(f"{label}: {name} is not valid JSON")
    if problems:
        return problems

    # bound hashes
    if grade.get("patch_sha256") != patch_sha:
        problems.append(f"{label}: grade.json patch_sha256 does not match final.patch")
    if grade.get("task_hash") != cur_task_hash:
        problems.append(f"{label}: grade.json task_hash is stale (task files changed; run regrade)")
    if grade.get("grader_digest") != cur["grader_digest"]:
        problems.append(f"{label}: grade.json grader_digest is stale (grader code, lockfiles or "
                        "toolchain changed; run regrade)")
    if aud.get("auditor_digest") != cur["auditor_digest"]:
        problems.append(f"{label}: audit.json auditor_digest is stale (audit.py or the leak "
                        "identifiers changed; run regrade)")
    if llm.get("stale"):
        problems.append(f"{label}: llm_grade.json is marked stale")
    for key, want in (("patch_sha256", patch_sha), ("task_hash", cur_task_hash),
                      ("grader_prompt_sha256", prompt_sha), ("model", llm_model)):
        if llm.get(key) != want:
            problems.append(f"{label}: llm_grade.json {key} is stale")
    if llm.get("status") not in ("graded", "not_graded"):
        problems.append(f"{label}: llm_grade.json status is {llm.get('status')!r}")
    elif (llm["status"] == "not_graded") != (not (adir / "final.patch").read_bytes().strip()):
        problems.append(f"{label}: llm_grade.json status does not fit the patch (empty <-> not_graded)")
    if aud.get("transcript_sha256") != sha256_file(adir / "transcript.jsonl"):
        problems.append(f"{label}: audit.json transcript_sha256 does not match transcript.jsonl")
    if aud.get("patch_sha256") != patch_sha:
        problems.append(f"{label}: audit.json patch_sha256 does not match final.patch")
    if cls.get("patch_sha256") != patch_sha:
        problems.append(f"{label}: classification.json patch_sha256 does not match final.patch")
    if cls.get("grade_sha256") != sha256_file(adir / "grade.json"):
        problems.append(f"{label}: classification.json grade_sha256 does not match grade.json")
    if cls.get("audit_sha256") is not None and cls["audit_sha256"] != sha256_file(adir / "audit.json"):
        problems.append(f"{label}: classification.json audit_sha256 does not match audit.json")
    if cls.get("stale"):
        problems.append(f"{label}: classification.json is marked stale")

    # classification content
    if not cls.get("confirmed"):
        problems.append(f"{label}: classification is not confirmed")
    outcome, verdict = cls.get("outcome"), grade.get("verdict")
    if outcome != "contaminated":
        want_outcome = {"PASS": "pass", "FAIL": "fail", "ERROR": "error"}.get(verdict)
        if outcome != want_outcome:
            problems.append(f"{label}: classification outcome {outcome!r} inconsistent with verdict {verdict!r}")
    if not aud.get("clean") and outcome != "contaminated" and not cls.get("audit_override"):
        problems.append(f"{label}: audit is not clean but classification is not contaminated")
    if aud.get("review_required") and not str(cls.get("review_cleared", "")).strip():
        problems.append(f"{label}: audit has review_required host-access pattern(s) not cleared at confirm")
    if outcome != "pass":
        if outcome != "contaminated" and cls.get("failure_source") not in SOURCES:
            problems.append(f"{label}: non-pass without a failure_source in {SOURCES}")
        if not str(cls.get("evidence", "")).strip():
            problems.append(f"{label}: non-pass with blank evidence")
    return problems


def main(argv=None) -> int:
    utf8_stdout()
    ap = argparse.ArgumentParser(prog="harness.report")
    ap.add_argument("--runs-dir", default=str(RUNS_DIR))
    ap.add_argument("--tasks-dir", default=str(TASKS_DIR))
    ap.add_argument("--corpus", default=str(CORPUS_PATH))
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="regenerate SUMMARY.md (default)")
    mode.add_argument("--check", action="store_true", help="read-only verification")
    args = ap.parse_args(argv)
    if args.check:
        problems = check(Path(args.runs_dir), Path(args.tasks_dir), Path(args.corpus))
        for p in problems:
            print(f"FAIL {p}")
        print(f"{len(problems)} problem(s)" if problems else "OK: run evidence is complete and current")
        return 1 if problems else 0
    print(f"wrote {write_summary(Path(args.runs_dir))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
